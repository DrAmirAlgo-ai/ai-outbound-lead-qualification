PACKS = {"en": EN, "ar": AR}


def normalize(lang: object) -> str:
    value = str(lang or "ar").strip().lower()
    return value if value in PACKS else "ar"


def translate(lang: object, key: str, **kwargs: object) -> str:
    pack = PACKS[normalize(lang)]
    text = pack.get(key) or EN.get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
